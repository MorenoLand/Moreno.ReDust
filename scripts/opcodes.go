func LookupOpcode(name string) uint16 {
	token := []byte(name)
	for i, value := range token {
		if value >= 'A' && value <= 'Z' {
			token[i] = value + ('a' - 'A')
		}
	}
	if id, ok := opcodeIDs[string(token)]; ok {
		return id
	}
	return 1
}

func LookupPascalOpcode(value []byte) uint16 {
	if len(value) == 0 || int(value[0]) > len(value)-1 {
		return 1
	}
	return LookupOpcode(string(value[1 : 1+int(value[0])]))
}
